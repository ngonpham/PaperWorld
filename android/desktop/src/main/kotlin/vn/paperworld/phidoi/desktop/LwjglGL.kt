package vn.paperworld.phidoi.desktop

import org.lwjgl.opengles.GLES30 as G
import org.lwjgl.opengles.GLES30
import vn.paperworld.phidoi.engine.GL
import java.nio.ByteBuffer

class LwjglGL : GL {
    private val exts: Set<String> by lazy { (0 until G.glGetInteger(GLES30.GL_NUM_EXTENSIONS)).mapNotNull { G.glGetStringi(GLES30.GL_EXTENSIONS, it) }.toSet() }
    override fun getString(name: Int): String? = G.glGetString(name)
    override fun getInteger(name: Int) = G.glGetInteger(name)
    override fun getError() = G.glGetError()
    override fun hasExtension(name: String) = name in exts
    override fun createShader(type: Int) = G.glCreateShader(type)
    override fun shaderSource(s: Int, src: String) = G.glShaderSource(s, src)
    override fun compileShader(s: Int) = G.glCompileShader(s)
    override fun getShaderCompiled(s: Int) = G.glGetShaderi(s, G.GL_COMPILE_STATUS) != 0
    override fun getShaderInfoLog(s: Int): String = G.glGetShaderInfoLog(s)
    override fun deleteShader(s: Int) = G.glDeleteShader(s)
    override fun createProgram() = G.glCreateProgram()
    override fun attachShader(p: Int, s: Int) = G.glAttachShader(p, s)
    override fun bindAttribLocation(p: Int, index: Int, name: String) = G.glBindAttribLocation(p, index, name)
    override fun linkProgram(p: Int) = G.glLinkProgram(p)
    override fun getProgramLinked(p: Int) = G.glGetProgrami(p, G.GL_LINK_STATUS) != 0
    override fun getProgramInfoLog(p: Int): String = G.glGetProgramInfoLog(p)
    override fun useProgram(p: Int) = G.glUseProgram(p)
    override fun getUniformLocation(p: Int, name: String) = G.glGetUniformLocation(p, name)
    override fun uniform1i(l: Int, v: Int) = G.glUniform1i(l, v)
    override fun uniform1f(l: Int, v: Float) = G.glUniform1f(l, v)
    override fun uniform2f(l: Int, a: Float, b: Float) = G.glUniform2f(l, a, b)
    override fun uniform3f(l: Int, a: Float, b: Float, c: Float) = G.glUniform3f(l, a, b, c)
    override fun uniform4f(l: Int, a: Float, b: Float, c: Float, d: Float) = G.glUniform4f(l, a, b, c, d)
    override fun uniformMatrix3fv(l: Int, m: FloatArray) = G.glUniformMatrix3fv(l, false, m)
    override fun uniformMatrix4fv(l: Int, m: FloatArray) = G.glUniformMatrix4fv(l, false, m)
    override fun genBuffer() = G.glGenBuffers()
    override fun deleteBuffer(b: Int) = G.glDeleteBuffers(b)
    override fun bindBuffer(target: Int, b: Int) = G.glBindBuffer(target, b)
    override fun bufferData(target: Int, data: ByteBuffer, usage: Int) = G.glBufferData(target, data, usage)
    override fun bufferData(target: Int, size: Int, usage: Int) = G.glBufferData(target, size.toLong(), usage)
    override fun bufferSubData(target: Int, offset: Int, data: ByteBuffer) = G.glBufferSubData(target, offset.toLong(), data)
    override fun genVertexArray() = G.glGenVertexArrays()
    override fun deleteVertexArray(v: Int) = G.glDeleteVertexArrays(v)
    override fun bindVertexArray(v: Int) = G.glBindVertexArray(v)
    override fun enableVertexAttribArray(i: Int) = G.glEnableVertexAttribArray(i)
    override fun disableVertexAttribArray(i: Int) = G.glDisableVertexAttribArray(i)
    override fun vertexAttribPointer(i: Int, size: Int, type: Int, normalized: Boolean, stride: Int, offset: Int) = G.glVertexAttribPointer(i, size, type, normalized, stride, offset.toLong())
    override fun vertexAttribDivisor(i: Int, d: Int) = G.glVertexAttribDivisor(i, d)
    override fun vertexAttrib4f(i: Int, a: Float, b: Float, c: Float, d: Float) = G.glVertexAttrib4f(i, a, b, c, d)
    override fun drawArrays(mode: Int, first: Int, count: Int) = G.glDrawArrays(mode, first, count)
    override fun drawElements(mode: Int, count: Int, type: Int, offset: Int) = G.glDrawElements(mode, count, type, offset.toLong())
    override fun drawArraysInstanced(mode: Int, first: Int, count: Int, instances: Int) = G.glDrawArraysInstanced(mode, first, count, instances)
    override fun drawElementsInstanced(mode: Int, count: Int, type: Int, offset: Int, instances: Int) = G.glDrawElementsInstanced(mode, count, type, offset.toLong(), instances)
    override fun genTexture() = G.glGenTextures()
    override fun deleteTexture(t: Int) = G.glDeleteTextures(t)
    override fun bindTexture(target: Int, t: Int) = G.glBindTexture(target, t)
    override fun activeTexture(unit: Int) = G.glActiveTexture(unit)
    override fun texImage2D(target: Int, level: Int, internalFormat: Int, w: Int, h: Int, format: Int, type: Int, data: ByteBuffer?) = G.glTexImage2D(target, level, internalFormat, w, h, 0, format, type, data)
    override fun texParameteri(target: Int, p: Int, v: Int) = G.glTexParameteri(target, p, v)
    override fun texParameterf(target: Int, p: Int, v: Float) = G.glTexParameterf(target, p, v)
    override fun generateMipmap(target: Int) = G.glGenerateMipmap(target)
    override fun pixelStorei(p: Int, v: Int) = G.glPixelStorei(p, v)
    override fun genFramebuffer() = G.glGenFramebuffers()
    override fun deleteFramebuffer(f: Int) = G.glDeleteFramebuffers(f)
    override fun bindFramebuffer(target: Int, f: Int) = G.glBindFramebuffer(target, f)
    override fun framebufferTexture2D(target: Int, attachment: Int, texTarget: Int, t: Int, level: Int) = G.glFramebufferTexture2D(target, attachment, texTarget, t, level)
    override fun framebufferRenderbuffer(target: Int, attachment: Int, rbTarget: Int, rb: Int) = G.glFramebufferRenderbuffer(target, attachment, rbTarget, rb)
    override fun checkFramebufferStatus(target: Int) = G.glCheckFramebufferStatus(target)
    override fun genRenderbuffer() = G.glGenRenderbuffers()
    override fun deleteRenderbuffer(r: Int) = G.glDeleteRenderbuffers(r)
    override fun bindRenderbuffer(target: Int, r: Int) = G.glBindRenderbuffer(target, r)
    override fun renderbufferStorage(target: Int, format: Int, w: Int, h: Int) = G.glRenderbufferStorage(target, format, w, h)
    override fun renderbufferStorageMultisample(target: Int, samples: Int, format: Int, w: Int, h: Int) = G.glRenderbufferStorageMultisample(target, samples, format, w, h)
    override fun blitFramebuffer(x0: Int, y0: Int, x1: Int, y1: Int, dx0: Int, dy0: Int, dx1: Int, dy1: Int, mask: Int, filter: Int) = G.glBlitFramebuffer(x0, y0, x1, y1, dx0, dy0, dx1, dy1, mask, filter)
    override fun drawBuffersNone() = G.glDrawBuffers(G.GL_NONE)
    override fun readBufferNone() = G.glReadBuffer(G.GL_NONE)
    override fun viewport(x: Int, y: Int, w: Int, h: Int) = G.glViewport(x, y, w, h)
    override fun clearColor(r: Float, g: Float, b: Float, a: Float) = G.glClearColor(r, g, b, a)
    override fun clear(mask: Int) = G.glClear(mask)
    override fun enable(cap: Int) = G.glEnable(cap)
    override fun disable(cap: Int) = G.glDisable(cap)
    override fun depthMask(on: Boolean) = G.glDepthMask(on)
    override fun depthFunc(f: Int) = G.glDepthFunc(f)
    override fun cullFace(m: Int) = G.glCullFace(m)
    override fun blendFunc(s: Int, d: Int) = G.glBlendFunc(s, d)
    override fun blendFuncSeparate(sRgb: Int, dRgb: Int, sA: Int, dA: Int) = G.glBlendFuncSeparate(sRgb, dRgb, sA, dA)
    override fun blendEquation(m: Int) = G.glBlendEquation(m)
    override fun colorMask(r: Boolean, g: Boolean, b: Boolean, a: Boolean) = G.glColorMask(r, g, b, a)
    override fun polygonOffset(factor: Float, units: Float) = G.glPolygonOffset(factor, units)
    override fun lineWidth(w: Float) = G.glLineWidth(w)
    override fun readPixels(x: Int, y: Int, w: Int, h: Int, format: Int, type: Int, out: ByteBuffer) = G.glReadPixels(x, y, w, h, format, type, out)
    override fun finish() = G.glFinish()
}
